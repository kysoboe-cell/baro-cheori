export function getGuide(slug: string) {
  return guides.find((guide) => guide.slug === slug);
}

/** 기둥 글이 참조할 수 있는 정적 경로 — 아래 assert가 이 목록을 함께 봅니다. */
const STATIC_PATHS = new Set([
  "/",
  "/about",
  "/guide",
  "/information-policy",
  "/privacy",
]);

/** `[[문구|/경로]]`와 related 링크가 실제로 존재하는 페이지인지 검사합니다. */
function pathExists(href: string) {
  if (STATIC_PATHS.has(href)) return true;

  const guideMatch = href.match(/^\/guide\/([^/#?]+)$/);
  if (guideMatch) return guides.some((guide) => guide.slug === guideMatch[1]);

  const problemMatch = href.match(/^\/problem\/([^/#?]+)$/);
  if (problemMatch) return Boolean(getProblem(problemMatch[1]));

  const serviceMatch = href.match(/^\/company\/([^/#?]+)\/([^/#?]+)$/);
  if (serviceMatch) return Boolean(getService(serviceMatch[1], serviceMatch[2]));

  const companyMatch = href.match(/^\/company\/([^/#?]+)$/);
  if (companyMatch) return Boolean(getCompany(companyMatch[1]));

  return false;
}

/**
 * 빌드 타임 가드레일입니다.
 * - 죽은 내부 링크가 있으면 빌드를 깨뜨립니다(죽은 링크 강한 기피 원칙).
 * - 글마다 본문 안 내부 링크가 3개 이상인지 확인합니다(지시서 1장 규칙).
 * - slug·제목·설명이 겹치지 않는지 확인합니다.
 */
(function assertGuides() {
  const slugs = new Set<string>();
  const descriptions = new Set<string>();

  for (const guide of guides) {
    if (slugs.has(guide.slug)) {
      throw new Error(`[guides] 중복 slug: ${guide.slug}`);
    }
    slugs.add(guide.slug);

    if (descriptions.has(guide.description)) {
      throw new Error(`[guides] 중복 description: ${guide.slug}`);
    }
    descriptions.add(guide.description);

    const bodyTexts: string[] = [];
    for (const section of guide.sections) {
      for (const block of section.blocks) {
        if (block.type === "p") bodyTexts.push(block.text);
        else if (block.type === "note") bodyTexts.push(block.text);
        else bodyTexts.push(...block.items);
      }
    }

    let inlineLinks = 0;
    for (const text of bodyTexts) {
      for (const match of text.matchAll(/\[\[([^\]|]+)\|([^\]]+)\]\]/g)) {
        inlineLinks += 1;
        if (!pathExists(match[2])) {
          throw new Error(
            `[guides] ${guide.slug}: 없는 페이지로 연결됩니다 — ${match[2]}`
          );
        }
      }
    }

    if (inlineLinks < 3) {
      throw new Error(
        `[guides] ${guide.slug}: 본문 안 내부 링크가 ${inlineLinks}개입니다(3개 이상 필요).`
      );
    }

    for (const link of guide.related ?? []) {
      if (!pathExists(link.href)) {
        throw new Error(
          `[guides] ${guide.slug}: related 링크가 없는 페이지입니다 — ${link.href}`
        );
      }
    }

    for (const related of guide.relatedGuides ?? []) {
      if (!guides.some((item) => item.slug === related)) {
        throw new Error(`[guides] ${guide.slug}: 없는 기둥 글 — ${related}`);
      }
    }
  }
})();
